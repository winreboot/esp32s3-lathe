#!/usr/bin/env python3
"""Writes arduino/esp32s3_lathe/, the firmware as an Arduino IDE sketch, from the PlatformIO sources.

    python tools/make_arduino.py

src/main.cpp stays the only copy of the code. This script copies it in as lathe.cpp and adds what the Arduino
IDE cannot do by itself:
  - FW_VERSION, read from platformio.ini (PlatformIO passes it as a build flag),
  - fonts_vlw.h: the display's digit fonts as C arrays (PlatformIO links fonts/*.vlw with embed_files),
  - art_png.h: the screen artwork art/*.png as C arrays,
  - web_page.h: data/index.html, gzipped, so the page is built into the firmware and no filesystem upload is needed.
Run it after any change to src/main.cpp, data/index.html or the fonts, and commit the result with them.
"""
import gzip, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'arduino', 'esp32s3_lathe')


def c_array(name, data, comment):
    rows = [', '.join('0x%02x' % b for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return '// %s\nstatic const uint8_t %s[%d] = {\n  %s\n};\n' % (comment, name, len(data), ',\n  '.join(rows))


def main():
    ini = open(os.path.join(ROOT, 'platformio.ini')).read()
    fw = re.search(r'-DFW_VERSION=\\"([0-9.]+)\\"', ini).group(1)
    html = open(os.path.join(ROOT, 'data', 'index.html'), 'rb').read()
    web = re.search(rb"WEB_VERSION='([0-9.]+)'", html).group(1).decode()
    src = open(os.path.join(ROOT, 'src', 'main.cpp')).read()
    if re.search(r'char\s+(ssid|pass)\[\d+\]\s*=\s*"[^"]+"', src):
        sys.exit('src/main.cpp has a Wi-Fi name or password filled in. Blank it before building the sketch.')

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'lathe.cpp'), 'w') as f:
        f.write('// Generated by tools/make_arduino.py from src/main.cpp. Edit src/main.cpp, not this file.\n'
                '#define FW_VERSION "%s"\n\n' % fw + src)

    fonts = '// Generated by tools/make_arduino.py from fonts/*.vlw (Oswald Bold, SIL Open Font License).\n#pragma once\n#include <stdint.h>\n'
    for key, fn in (('big', 'd_big.vlw'), ('mid', 'd_mid.vlw'), ('small', 'd_small.vlw'), ('tbig', 't_big.vlw'), ('tsmall', 't_small.vlw'), ('rpm', 'd_rpm.vlw'), ('tmid', 't_mid.vlw'), ('txl', 't_xl.vlw')):
        data = open(os.path.join(ROOT, 'fonts', fn), 'rb').read()
        fonts += c_array('vlw_%s_data' % key, data, fn)
        fonts += 'static const uint8_t *const vlw_{0}_start = vlw_{0}_data, *const vlw_{0}_end = vlw_{0}_data + sizeof vlw_{0}_data;\n\n'.format(key)
    open(os.path.join(OUT, 'fonts_vlw.h'), 'w').write(fonts)

    art = '// Generated by tools/make_arduino.py from art/*.png (drawn by tools/make_art.py).\n#pragma once\n#include <stdint.h>\n'
    names = ('plain', 'rpm', 'menu', 'keypad', 'info', 'view', 'main', 'xz', 'thread', 'diag', 'mat', 'numpad', 'tools', 'pick')
    for name in names + tuple(n + '_k' for n in names):
        data = open(os.path.join(ROOT, 'art', name + '.png'), 'rb').read()
        art += c_array('art_%s_data' % name, data, name + '.png')
        art += 'static const uint8_t *const art_{0}_start = art_{0}_data, *const art_{0}_end = art_{0}_data + sizeof art_{0}_data;\n\n'.format(name)
    open(os.path.join(OUT, 'art_png.h'), 'w').write(art)

    gz = gzip.compress(html, compresslevel=9, mtime=0)
    open(os.path.join(OUT, 'web_page.h'), 'w').write(
        '// Generated by tools/make_arduino.py: data/index.html (page v%s), gzipped.\n#pragma once\n#include <stdint.h>\n' % web
        + c_array('WEB_PAGE_GZ', gz, 'index.html, %d bytes before compression' % len(html)))

    ino = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'arduino_ino.txt')).read()
    open(os.path.join(OUT, 'esp32s3_lathe.ino'), 'w').write(ino.replace('{FW}', fw).replace('{WEB}', web))
    print('arduino/esp32s3_lathe: firmware %s, page %s (%d KB gzipped)' % (fw, web, len(gz) // 1024))


if __name__ == '__main__':
    main()
